"""HANDOFF 231ck: the loop is only half closed -- does a better TEACHER make better data?

Every batch so far (n1, sf1, sf2, sf3) was generated by the SAME player: the port carrying
sploppy's `example.nnue` at 50,000 nodes. Training iterates (mix_train_s3 starts from batch 2's
net if it measured better), but the thing that MAKES the data never improves, so every batch is
a fresh sample of one fixed teacher's opinions. In a self-play loop that is the half that pays:
a stronger teacher gives sharper labels and, because it also chooses the moves, a position
distribution nearer the play we care about.

The experiment, as controlled as this can be made:
  * 200 games with a CERTIFIED stronger teacher, at sf1's own seed -- `game_seed` is
    `seed * 1000003 + game_id * 7919`, so games 0..199 get sf1's random opening plies and sf1's
    random-move plan. The two batches therefore start from identical openings and diverge only
    where the teacher's own search chooses differently.
  * the control is sf1's games 0..199, re-packed from its shards -- no generation needed, and
    the same code wrote them.
  * both imported the same way (--min-ply 16, no PV rows, sf1's records predate the PV patch),
    both trained alone from example.nnue with one recipe, the same seed and the SAME step count
    (the smaller row count decides), both evaluated on the same openings and seed.
Two nets, one difference: who labelled the rows.

"Certified" means the node-limited SPRT (231cf) said that net beats `example.nnue` IN THE PORT.
That matters: sploppy's own eval scored n1_25k at .595 (+67 Elo) against example, but it runs
sploppy's Rust search; the generator and the gates run the C++ port, where the 500 ms gate could
not separate them. The teacher's job is to search well in the port, so the port's verdict is the
one that may promote it. If nothing is certified this arm does not run: without a stronger
teacher there is nothing to test.

It waits for every registered job (both chains, the gates, the sweep and all the arms), so it
can only ever use CPU nobody else has claimed. Screening, not shipping.

No sys.argv; constants below.
"""
import datetime
import gzip
import hashlib
import json
import os
import subprocess
import time

# --- paths, anchored on this file so a fresh checkout runs unchanged
_ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
_WORK = os.path.join(_ROOT, "work")   # intermediate outputs; mkdir it once

S = _WORK
T = _ROOT + "/nnue_train"
REPO = os.path.join(T, "sploppy_repo")
VPY = os.path.join(T, ".venv", "bin", "python")
BOT = os.path.join(REPO, "target", "release", "bot")
INIT = "models/nnue/examples/example.nnue"
GEN_SRC = os.path.join(T, "sf19nn_selfplay.py")  # the exact program that made the control, by line rewrite
SRC_RECORDS = "sf1_ex_50k"                       # the control batch, and the seed the new one reuses
GAMES = 200
NODES = 50000
WORKERS = 4
SEED_GEN = 20260925                              # sf1's seed: games 0..199 get sf1's openings
MIN_PLY = 16
NEW_RECORDS = "t1_up_50k"                        # the new batch (teacher: the promoted net)
CTL_RECORDS = "t1_ex_50k"                        # sf1's first GAMES games, re-packed
HIDDEN, BATCH, EPOCHS, PASSES, LR = 512, 2048, 20, 20, 0.0001   # 20 passes: 50k rows, not 800k
SEED_TRAIN = 20260926
THREADS, NICE = 2, 15
EVAL_PAIRS, EVAL_SIMS, EVAL_SEED = 100, 8, 20260927
H2H_PAIRS, H2H_SEED = 300, 20260945       # the decisive number: the two students against each other
POLL_S = 120
ATTEMPTS = 3
OUT = os.path.join(S, "teacher_arm.log")
WAIT_FOR = ("after_gates.py", "mix_train", "[0-9]_gates.py", "sweep_s1.py", "wdl_arm.py",
            "pv_arm.py", "v9_arm.py", "sf1_chain.py", "sf2_chain.py", "sf3_chain.py",
            "nodes_queue.py", "nodes_gate_", "node_scaling.py", "n1n_gate.py", "scale_arm.py")
# (frozen net, the node-SPRT log that would certify it), best first
TEACHERS = [(os.path.join(S, "ab_s3_bin", "sf3_ex_50k.nnue"), os.path.join(S, "nodes_gate_s3n.log")),
            (os.path.join(S, "ab_s2_bin", "sf2_ex_50k.nnue"), os.path.join(S, "nodes_gate_s2n.log")),
            (os.path.join(S, "ab_s1_bin", "sf1_ex_50k.nnue"), os.path.join(S, "nodes_gate_s1n.log")),
            (os.path.join(S, "ab_n1_bin", "n1_25k.nnue"), os.path.join(S, "nodes_gate_n1n.log"))]



def _usable(path):
    """A cached eval counts only if it parses. `stdout=open(path, "w")` creates the file the
    instant the eval starts, so a killed eval leaves a 0-byte file that looks like a finished
    one; the next run would then skip the eval and die on json.load. Checked, not assumed."""
    try:
        json.load(open(path))
        return True
    except Exception:
        return False

def say(text):
    line = "%s TEACH %s" % (datetime.datetime.now().strftime("%m-%d %H:%M:%S"), text)
    with open(OUT, "a") as fh:
        fh.write(line + "\n")
    print(line, flush=True)


def alive(pattern):
    return subprocess.run(["pgrep", "-f", pattern], capture_output=True).returncode == 0


def read(path):
    return open(path, errors="replace").read() if os.path.exists(path) else ""


def rows_of(name):
    path = os.path.join(REPO, "runs", "nnue_data", name, "provenance.json")
    return json.load(open(path))["rows"] if os.path.exists(path) else None


def wait_its_turn():
    said = False
    while True:
        busy = [x for x in WAIT_FOR if alive(x)]
        if not busy:
            return
        if not said:
            say("waiting for %s" % ", ".join(busy))
            said = True
        time.sleep(POLL_S)


def certified():
    """The best net a node-limited SPRT called stronger than example.nnue in the port."""
    for net, log in TEACHERS:
        if not os.path.exists(net):
            continue
        text = read(log)
        if "(H1 " in text and "VERDICT" in text:      # "(H1 +10 accepted)": the CANDIDATE is stronger
            line = [x for x in text.splitlines() if "(H1 " in x][-1]
            return net, log, line.strip()
    return None, None, None


def rewrite(src, dst, pairs):
    out, hits = [], [0] * len(pairs)
    for line in open(src).read().splitlines(True):
        for i, (prefix, new) in enumerate(pairs):
            if line.startswith(prefix):
                hits[i] += 1
                out.append(new + "\n")
                break
        else:
            out.append(line)
    for i, (prefix, _) in enumerate(pairs):
        assert hits[i] == 1, "%s: %d lines start with %r" % (dst, hits[i], prefix)
    open(dst, "w").write("".join(out))


def games_in(man):
    return sum(s.get("counts", {}).get("games", 0) for s in man.get("shards", []))


def manifest_of(name):
    path = os.path.join(REPO, "runs", "nnue_selfplay", name, "manifest.json")
    return json.load(open(path)) if os.path.exists(path) else None


def records_complete(name):
    """A records dir is only usable once the generator has PACKED it: parts are not shards."""
    man = manifest_of(name)
    return bool(man) and bool(man.get("shards")) and games_in(man) >= GAMES


def generate(teacher):
    if records_complete(NEW_RECORDS):
        say("%s already generated" % NEW_RECORDS)
        return True
    gen = os.path.join(S, "teacher_gen.py")
    rewrite(GEN_SRC, gen, [("HERE = ", 'HERE = "%s"' % T),          # the copy lives in $S; REPO hangs off HERE
                           ("NET = ", 'NET = "%s"' % teacher),
                           ("NAME = ", 'NAME = "%s"' % NEW_RECORDS),
                           ("GAMES = ", "GAMES = %d" % GAMES),
                           ("NODES = ", "NODES = %d" % NODES),
                           ("WORKERS = ", "WORKERS = %d" % WORKERS),
                           ("SEED = ", "SEED = %d" % SEED_GEN)])
    say("generating %d games with %s at %d nodes, %d workers, seed %d"
        % (GAMES, os.path.basename(teacher), NODES, WORKERS, SEED_GEN))
    for attempt in range(1, ATTEMPTS + 1):
        rc = subprocess.run([VPY, "-u", gen], cwd=T, stdout=open(os.path.join(S, "teacher_arm.gen"), "a"),
                            stderr=subprocess.STDOUT).returncode
        if rc == 0 and records_complete(NEW_RECORDS):
            say("generated %s" % NEW_RECORDS)
            return True
        say("generator attempt %d rc %d (it resumes from its own manifest)" % (attempt, rc))
        time.sleep(60)
    say("GAVE UP generating")
    return False


def control():
    """sf1's first GAMES games, re-packed as their own records directory."""
    src = os.path.join(REPO, "runs", "nnue_selfplay", SRC_RECORDS)
    dst = os.path.join(REPO, "runs", "nnue_selfplay", CTL_RECORDS)
    if records_complete(CTL_RECORDS):
        say("%s already packed" % CTL_RECORDS)
        return True
    man = manifest_of(SRC_RECORDS)
    if not man or not man.get("shards"):
        say("STOP: %s is not packed yet (parts are not shards)" % SRC_RECORDS)
        return False
    os.makedirs(dst, exist_ok=True)
    kept, roots, labelled = [], 0, 0
    shard = os.path.join(dst, "shard-000000.jsonl.gz")
    with gzip.open(shard, "wt", encoding="utf-8") as out:
        for entry in man.get("shards", []):
            with gzip.open(os.path.join(src, entry["file"]), "rt", encoding="utf-8") as lines:
                for line in lines:
                    rec = json.loads(line)
                    if rec.get("game_id", -1) < GAMES:
                        out.write(line if line.endswith("\n") else line + "\n")
                        kept.append(rec["game_id"])
                        roots += len(rec.get("roots", []))
                        labelled += sum(1 for r in rec.get("roots", []) if r.get("root_score") is not None)
            if len(kept) >= GAMES:
                break
    if not kept:
        say("STOP: no game with game_id < %d in %s" % (GAMES, SRC_RECORDS))
        return False
    new = dict(man)                                   # keeps score_scale, rules, producer, settings
    new["shards"] = [{"file": "shard-000000.jsonl.gz", "first_game": min(kept),
                      "sha256": hashlib.sha256(open(shard, "rb").read()).hexdigest(),
                      "bytes": os.path.getsize(shard),
                      "counts": {"games": len(kept), "roots": roots, "labelled_roots": labelled}}]
    new["complete"] = len(kept) >= GAMES
    new["derived_from"] = {"records": SRC_RECORDS, "rule": "game_id < %d" % GAMES,
                           "why": "the control for the teacher arm: the same openings, the old teacher"}
    json.dump(new, open(os.path.join(dst, "manifest.json"), "w"), indent=1)
    say("control: %d games of %s re-packed as %s" % (len(kept), SRC_RECORDS, CTL_RECORDS))
    return len(kept) >= GAMES


def imported(records, set_name):
    if rows_of(set_name):
        say("%s already imported: %d rows" % (set_name, rows_of(set_name)))
        return True
    cmd = [VPY, "-u", "-m", "nnue.importer", "selfplay",
           "--records", os.path.join("runs", "nnue_selfplay", records),
           "--out", set_name, "--min-ply", str(MIN_PLY)]
    rc = subprocess.run(cmd, cwd=REPO, stdout=open(os.path.join(S, "teacher_arm.import"), "a"),
                        stderr=subprocess.STDOUT).returncode
    if rc != 0 or not rows_of(set_name):
        say("import rc %d for %s" % (rc, set_name))
        return False
    rc = subprocess.run([VPY, "-u", "-m", "nnue.data", "encode", set_name], cwd=REPO,
                        stdout=open(os.path.join(S, "teacher_arm.import"), "a"),
                        stderr=subprocess.STDOUT).returncode
    say("%s: %d rows, encode rc %d" % (set_name, rows_of(set_name), rc))
    return rc == 0


def train(tag, run, set_name, steps):
    run_dir = os.path.join(REPO, "runs", run)
    out = os.path.join(S, "teacher_arm_%s.out" % tag)
    if os.path.exists(os.path.join(run_dir, "best.nnue")):
        say("%s already trained" % tag)
        return True
    warmup = min(200, max(1, steps * EPOCHS // 10))
    cmd = ["nice", "-n", str(NICE), VPY, "-u", "-m", "nnue.train", "--run", run, "--init", INIT,
           "--hidden", str(HIDDEN), "--version", "8", "--batch", str(BATCH),
           "--steps_per_epoch", str(steps), "--epochs", str(EPOCHS), "--lr", str(LR),
           "--weight_decay", "1e-5", "--warmup_steps", str(warmup), "--lr_floor", "0.15",
           "--qat_start_epoch", "1", "--raw_weight", "0.02", "--symmetry_weight", "0.2",
           "--grad_clip", "5", "--patience", str(EPOCHS), "--val_rows", "8192",
           "--threads", str(THREADS), "--device", "cpu", "--seed", str(SEED_TRAIN),
           "--data", "%s:1.0" % set_name]
    say("%s: training on %s alone, %d x %d steps" % (tag, set_name, EPOCHS, steps))
    rc = subprocess.run(cmd, cwd=REPO, stdout=open(out, "a"), stderr=subprocess.STDOUT).returncode
    ok = rc == 0 and os.path.exists(os.path.join(run_dir, "best.nnue"))
    say("%s: train rc %d%s" % (tag, rc, "" if ok else " -- no best.nnue"))
    return ok


def screen(tag, run):
    path = os.path.join(REPO, "runs", run, "eval_sweep.json")
    if not _usable(path):
        cmd = ["nice", "-n", str(NICE), BOT, "eval",
               "--candidate", "nnue:runs/%s/best.nnue?hash=64" % run,
               "--reference", "nnue:%s?hash=64" % INIT,
               "--sims", str(EVAL_SIMS), "--pairs", str(EVAL_PAIRS),
               "--threads", str(THREADS), "--seed", str(EVAL_SEED)]
        rc = subprocess.run(cmd, cwd=REPO, stdout=open(path + ".part", "w"),
                            stderr=open(os.path.join(S, "teacher_arm.err"), "a")).returncode
        if rc == 0:
            os.replace(path + ".part", path)  # never leave a half-written eval that looks cached
        if rc != 0:
            say("%s: eval rc %d" % (tag, rc))
            return None
    ev = json.load(open(path))
    games = ev["wins"] + ev["draws"] + ev["losses"]
    ev["score"] = (ev["wins"] + 0.5 * ev["draws"]) / games if games else None
    say("%s: score %.3f over %d games (W/D/L %d/%d/%d), bootstrap %s"
        % (tag, ev["score"], games, ev["wins"], ev["draws"], ev["losses"], ev.get("bootstrap_interval")))
    return ev


def head_to_head():
    """up vs ex directly. Two screens against example.nnue carry two lots of noise; this carries one,
    and it is the question in one match: whose student plays better."""
    path = os.path.join(REPO, "runs", "teacher_up", "eval_h2h.json")
    if not _usable(path):
        cmd = ["nice", "-n", str(NICE), BOT, "eval",
               "--candidate", "nnue:runs/teacher_up/best.nnue?hash=64",
               "--reference", "nnue:runs/teacher_ex/best.nnue?hash=64",
               "--sims", str(EVAL_SIMS), "--pairs", str(H2H_PAIRS),
               "--threads", str(THREADS), "--seed", str(H2H_SEED)]
        say("head to head: %d pairs at %d nodes, up as candidate" % (H2H_PAIRS, EVAL_SIMS * 2500))
        rc = subprocess.run(cmd, cwd=REPO, stdout=open(path + ".part", "w"),
                            stderr=open(os.path.join(S, "teacher_arm.err"), "a")).returncode
        if rc == 0:
            os.replace(path + ".part", path)  # never leave a half-written eval that looks cached
        if rc != 0:
            say("head to head: eval rc %d" % rc)
            return None
    ev = json.load(open(path))
    games = ev["wins"] + ev["draws"] + ev["losses"]
    ev["score"] = (ev["wins"] + 0.5 * ev["draws"]) / games if games else None
    say("H2H up vs ex: score %.3f over %d games (W/D/L %d/%d/%d), bootstrap %s"
        % (ev["score"], games, ev["wins"], ev["draws"], ev["losses"], ev.get("bootstrap_interval")))
    return ev


def main():
    say("started pid %d" % os.getpid())
    wait_its_turn()
    teacher, log, verdict = certified()
    if not teacher:
        say("STOP: no net has been certified stronger than example.nnue in the port "
            "(node SPRT logs: %s). Nothing to test, nothing run."
            % ", ".join(os.path.basename(x[1]) for x in TEACHERS))
        return
    say("teacher: %s, certified by %s" % (os.path.basename(teacher), os.path.basename(log)))
    say("verdict line: %s" % verdict[:200])
    if not generate(teacher) or not control():
        return
    if not imported(NEW_RECORDS, "selfplay_" + NEW_RECORDS):
        return
    if not imported(CTL_RECORDS, "selfplay_" + CTL_RECORDS):
        return
    rows = min(rows_of("selfplay_" + NEW_RECORDS), rows_of("selfplay_" + CTL_RECORDS))
    steps = max(10, (rows * PASSES + BATCH * EPOCHS - 1) // (BATCH * EPOCHS))
    say("rows: new %d, control %d -> both train %d x %d steps"
        % (rows_of("selfplay_" + NEW_RECORDS), rows_of("selfplay_" + CTL_RECORDS), EPOCHS, steps))
    done = []
    for tag, run, set_name in (("up", "teacher_up", "selfplay_" + NEW_RECORDS),
                               ("ex", "teacher_ex", "selfplay_" + CTL_RECORDS)):
        if train(tag, run, set_name, steps):
            done.append((tag, run, screen(tag, run)))
    say("TABLE  teacher | rows | eval score vs example.nnue (same openings, same seed)")
    for tag, run, ev in done:
        say("TABLE  %s | %s | %s" % (tag, rows_of("selfplay_" + (NEW_RECORDS if tag == "up" else CTL_RECORDS)),
                                     ("%.3f" % ev["score"]) if ev else "?"))
    if len(done) == 2 and all(ev for _, _, ev in done):
        head_to_head()
    say("READ: the two nets differ only in who labelled and chose the moves. A clear win for 'up' "
        "promotes the teacher for every later batch; a tie says the loop's data is not teacher-limited.")
    say("DONE. Nothing shipped")


main()
